"""Turn origin: whose words are in a user turn, from Claude Code's own markers only (connectors-claude-code-and-codex.md
§8; MEMORY-ARCHITECTURE §2.2, I3, I20, I24).

A prompt that reaches a hook, or a user line in a transcript, can hold several kinds of text. `classify` splits it
into spans, each with one origin:

- typed: what the person typed (the default);
- pasted: Claude Code's pasted-text markers, `<pasted_content>...</pasted_content>` and `[Pasted text #1 +20 lines]`
  (and any ranges the caller already knows from the transcript);
- command: a slash command or a shell command the person typed (`<command-name>`, `<bash-input>`, or a prompt that
  starts with `/name`); the words after it are typed;
- command_output: what a command printed (`<local-command-stdout>`, `<bash-stdout>`);
- system_injection: text a hook or Claude Code added, which is not the user's words (`<system-reminder>`,
  `<command-contents>`, `<task-notification>`, the compaction summary, an interrupt marker, ...);
- northstar_injected: a block Northstar delivered, wrapped in its own marker (`NORTHSTAR_TAG`). It wins over
  everything around it, even inside a `<system-reminder>`, so it is never taken for the user's words (I24).

`model_reported` never arises on Claude Code: both sides arrive word for word.

Nothing here calls a model. The classes are not the same as §8's table: that one is the adapter's label for a whole
turn and C06's binding of it. This is the layer under it, from markers alone; a heuristic such as paste demotion
(§8) is a later step and not done here.
"""

from __future__ import annotations

import heapq
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal, Sequence

from northstar_agent_memory import paths

SpanOrigin = Literal["typed", "pasted", "command", "command_output", "system_injection", "northstar_injected"]

# The marker Northstar wraps its own delivered text in (the delivery step, later, uses wrap_northstar).
NORTHSTAR_TAG = "northstar-context"

# Whose words each origin is, and how the history store labels it.
SPEAKER_FOR: dict[str, str] = {
    "typed": "user",
    "pasted": "user",
    "command": "user",
    "command_output": "system",
    "system_injection": "system",
    "northstar_injected": "northstar",
}
STORE_ORIGIN_FOR: dict[str, str] = {
    "typed": "typed",
    "pasted": "pasted",
    "command": "typed",
    "command_output": "tool_output",
    "system_injection": "tool_output",
    "northstar_injected": "northstar_injected",
}
USER_ORIGINS = frozenset({"typed", "pasted", "command"})

# Tags Claude Code and its hooks write, and what the text inside them is.
_BLOCK_ORIGIN: dict[str, str] = {
    "system-reminder": "system_injection",
    "user-prompt-submit-hook": "system_injection",
    "local-command-caveat": "system_injection",
    "task-notification": "system_injection",
    "skill-format": "system_injection",
    "command-message": "system_injection",  # the command's name again, without the slash
    "command-contents": "system_injection",  # the expanded template, not the user's words
    "command-name": "command",
    "bash-input": "command",
    "local-command-stdout": "command_output",
    "local-command-stderr": "command_output",
    "bash-stdout": "command_output",
    "bash-stderr": "command_output",
}
_MARKUP_ONLY = ("command-args",)  # the tags are dropped; what is inside is typed
_PRIORITY = {"typed": 0, "pasted": 1, "command": 2, "command_output": 2, "system_injection": 3, "northstar_injected": 5}
_MARKUP = 10  # tag text itself: in no span

_TAGS = "|".join(re.escape(t) for t in (*_BLOCK_ORIGIN, *_MARKUP_ONLY))
# Opening tags take at most 200 attribute characters, so an unclosed "<tag " run cannot make a scan quadratic.
_OPEN = re.compile(rf"<(?P<tag>{_TAGS})\b[^>]{{0,200}}>")
_OPEN_NORTHSTAR = re.compile(rf"<(?P<tag>{NORTHSTAR_TAG})\b[^>]{{0,200}}>")
_OPEN_PASTE = re.compile(r"<(?P<tag>pasted_content)\b[^>]{0,200}>")
_CLOSE: dict[str, re.Pattern[str]] = {
    t: re.compile(rf"</{re.escape(t)}\b[^>]{{0,200}}>") for t in (*_BLOCK_ORIGIN, *_MARKUP_ONLY, NORTHSTAR_TAG, "pasted_content")
}
_PASTE_MARKER = re.compile(r"\[Pasted text #\d+(?: \+\d+ lines?)?\]")
_SLASH = re.compile(r"/[A-Za-z][\w:\-]*(?=\s|$)")

# A whole turn Claude Code or a harness wrote as a user line.
_SYSTEM_PREFIXES = (
    "[Request interrupted by user",
    "This session is being continued from a previous conversation",
    "Caveat: The messages below were generated by the user",
    "[SYSTEM NOTIFICATION",
    "Base directory for this skill:",
)


def wrap_northstar(text: str) -> str:
    """Northstar's delivered text inside its marker. Any marker already in the text is removed, so one block stays one."""
    clean = re.sub(rf"</?{NORTHSTAR_TAG}\b[^>]*>", "", text)
    return f"<{NORTHSTAR_TAG}>\n{clean}\n</{NORTHSTAR_TAG}>"


def contains_northstar_block(text: str) -> bool:
    return bool(_blocks(text, _OPEN_NORTHSTAR))


def inside_data_root(folder: str | Path | None) -> bool:
    """True when a working folder is inside Northstar's own data root: its own runs start there and are never
    captured as the user's sessions (I24)."""
    if not folder:
        return False
    try:
        return Path(folder).expanduser().resolve().is_relative_to(paths.data_root().resolve())
    except (OSError, ValueError, RuntimeError):
        return False


@dataclass(frozen=True, slots=True)
class Span:
    """A stretch of the turn, [start, end) in the raw text, with one origin. `tag` names the wrapper it came from."""

    start: int
    end: int
    origin: SpanOrigin
    tag: str | None = None

    def text(self, raw: str) -> str:
        return raw[self.start : self.end]


@dataclass(slots=True)
class TurnParts:
    """A turn split by origin. `user_text` is the user's own words (typed, pasted, command), word for word, with
    the wrappers and injections cut out; `paste_ranges` are offsets into it. Northstar's blocks come out whole."""

    spans: list[Span]
    user_text: str = ""
    paste_ranges: list[tuple[int, int]] = field(default_factory=list)
    command: str | None = None
    northstar: list[str] = field(default_factory=list)
    dropped: dict[str, int] = field(default_factory=dict)  # spans left out, by origin

    @property
    def user_origin(self) -> str:
        """pasted when the user's words are all pasted text, else typed (a mix is typed, with `paste_ranges`)."""
        if self.paste_ranges == [(0, len(self.user_text))] and self.user_text:
            return "pasted"
        return "typed"


@dataclass(frozen=True, slots=True)
class _Block:
    tag: str
    start: int
    inner_start: int
    inner_end: int
    end: int


def _blocks(raw: str, opener: re.Pattern[str] = _OPEN) -> list[_Block]:
    """Every <tag>...</tag> block of the tags `opener` names, in order, none inside another found block. A tag with no
    closer left is not searched again, so the scan stays linear however many unclosed tags there are."""
    out: list[_Block] = []
    dead: set[str] = set()
    pos = 0
    while True:
        m = opener.search(raw, pos)
        if m is None:
            return out
        tag = m.group("tag")
        close = None if tag in dead else _CLOSE[tag].search(raw, m.end())
        if close is None:
            dead.add(tag)
            pos = m.end()
            continue
        out.append(_Block(tag, m.start(), m.end(), close.start(), close.end()))
        pos = close.end()


def _segments(raw: str, extra_pasted: Sequence[tuple[int, int]] = ()) -> list[Span]:
    """The turn cut at every boundary, untrimmed: each piece with its origin; tag markup is left out."""
    n = len(raw)
    if raw.lstrip().startswith(_SYSTEM_PREFIXES):
        return [Span(0, n, "system_injection", "prefix")]
    # (priority, start, end, origin, tag); origin None marks tag text.
    paint: list[tuple[int, int, int, str | None, str | None]] = [(0, 0, n, "typed", None)]

    def markup(start: int, end: int) -> None:
        if end > start:
            paint.append((_MARKUP, start, end, None, None))

    has_command_tag = False
    for b in _blocks(raw):
        tag = b.tag
        markup(b.start, b.inner_start)
        markup(b.inner_end, b.end)
        if tag in _MARKUP_ONLY:
            continue
        origin = _BLOCK_ORIGIN[tag]
        has_command_tag |= tag == "command-name"
        paint.append((_PRIORITY[origin], b.inner_start, b.inner_end, origin, tag))
    for b in _blocks(raw, _OPEN_NORTHSTAR):
        markup(b.start, b.inner_start)
        markup(b.inner_end, b.end)
        paint.append((_PRIORITY["northstar_injected"], b.inner_start, b.inner_end, "northstar_injected", NORTHSTAR_TAG))
    for b in _blocks(raw, _OPEN_PASTE):
        markup(b.start, b.inner_start)
        markup(b.inner_end, b.end)
        paint.append((_PRIORITY["pasted"], b.inner_start, b.inner_end, "pasted", "pasted_content"))
    for m in _PASTE_MARKER.finditer(raw):
        paint.append((_PRIORITY["pasted"], m.start(), m.end(), "pasted", "paste_marker"))
    for start, end in extra_pasted:
        if 0 <= start < end <= n:
            paint.append((_PRIORITY["pasted"], start, end, "pasted", "transcript"))
    if not has_command_tag:
        lead = raw[: n - len(raw.lstrip())]
        slash = _SLASH.match(raw, len(lead))
        if slash:
            paint.append((_PRIORITY["command"], slash.start(), slash.end(), "command", "slash"))

    cuts = sorted({0, n, *(p[1] for p in paint), *(p[2] for p in paint)})
    by_start = sorted(range(len(paint)), key=lambda i: paint[i][1])
    heap: list[tuple[int, int]] = []  # (-priority, position in paint): the earliest of equal priorities wins
    nxt = 0
    out: list[Span] = []
    for lo, hi in zip(cuts, cuts[1:]):
        while nxt < len(by_start) and paint[by_start[nxt]][1] <= lo:
            heapq.heappush(heap, (-paint[by_start[nxt]][0], by_start[nxt]))
            nxt += 1
        while paint[heap[0][1]][2] <= lo:  # ended before this piece (the base paint never does)
            heapq.heappop(heap)
        _, _, _, origin, tag = paint[heap[0][1]]
        if origin is None:
            continue
        last = out[-1] if out else None
        if last is not None and last.end == lo and (last.origin, last.tag) == (origin, tag):
            out[-1] = Span(last.start, hi, origin, tag)  # type: ignore[arg-type]
        else:
            out.append(Span(lo, hi, origin, tag))  # type: ignore[arg-type]
    return out


def classify(raw: str, extra_pasted: Sequence[tuple[int, int]] = ()) -> list[Span]:
    """The origin of each stretch of a user turn, in order. Spans do not overlap and leave out the wrapper tags and
    whitespace between pieces. `extra_pasted` are paste ranges the caller learned elsewhere (the transcript)."""
    spans: list[Span] = []
    for seg in _segments(raw, extra_pasted):
        piece = raw[seg.start : seg.end]
        lead = len(piece) - len(piece.lstrip())
        body = piece.strip()
        if not body:
            continue
        spans.append(Span(seg.start + lead, seg.start + lead + len(body), seg.origin, seg.tag))
    return spans


def split_turn(raw: str, extra_pasted: Sequence[tuple[int, int]] = ()) -> TurnParts:
    """Split a user turn into the user's words, Northstar's blocks and what is left out."""
    parts = TurnParts(spans=classify(raw, extra_pasted))
    pieces: list[str] = []
    ranges: list[tuple[int, int]] = []
    size = 0
    gap = False  # something was cut out since the last kept piece
    prev_end = 0
    for seg in _segments(raw, extra_pasted):
        body = raw[seg.start : seg.end]
        gap = gap or seg.start > prev_end  # tag text between the pieces
        prev_end = seg.end
        if seg.origin == "northstar_injected":
            if body.strip():
                parts.northstar.append(body.strip())
            gap = True
            continue
        if seg.origin not in USER_ORIGINS:
            if body.strip():
                parts.dropped[seg.origin] = parts.dropped.get(seg.origin, 0) + 1
            gap = True
            continue
        if seg.tag == "command-name":
            name = body.strip()
            body = name if name.startswith("/") else "/" + name
            parts.command = body
        elif seg.tag == "slash":
            parts.command = body.strip()
        if gap and pieces and not pieces[-1][-1:].isspace() and not body[:1].isspace():
            pieces.append(" ")
            size += 1
        gap = False
        if seg.origin == "pasted" and body.strip():
            ranges.append((size, size + len(body)))
        pieces.append(body)
        size += len(body)
    joined = "".join(pieces)
    lead = len(joined) - len(joined.lstrip())
    text = joined.strip()
    parts.user_text = text
    parts.paste_ranges = [
        (max(s - lead, 0), min(e - lead, len(text))) for s, e in ranges if min(e - lead, len(text)) > max(s - lead, 0)
    ]
    return parts
