"""Read Claude Code transcripts into neutral chat records (DESIGN §8, §9).

Claude Code writes one JSONL file per session under ~/.claude/projects/<project>/
(note 22 A12). The vendor calls the format internal ([CX] §12), so this reader is
tolerant: a line it does not know is counted and skipped, never fatal. The measures
from normal use (normal_use.py) run on what it returns, first on the sessions from
before Northstar; live capture uses hooks instead.

A typed user turn is what the person typed (MEMORY-ARCHITECTURE §2.2, origin "typed").
These are not typed turns: tool results, isMeta lines, sidechains (subagents),
compaction summaries, interrupt markers, and Claude Code's wrappers such as
<command-name>, <local-command-stdout> and <system-reminder>. A slash command typed
with words after it ("/review the tie-break") is kept, with its name in
meta["command"]; a bare command ("/clear") is not a turn. Pasted text
(<pasted_content>) is kept, with its offsets in meta["paste_ranges"].
"""

from __future__ import annotations

import hashlib
import json
import re
from collections import Counter
from dataclasses import dataclass, field
from datetime import date, datetime, time, timezone
from pathlib import Path

from northstar_agent_memory.transcript import Message, Source

APP = "claude-code"
FAMILY = "anthropic"  # every model Claude Code runs

# Line types this reader knows; any other is counted as "unknown:<type>".
KNOWN_TYPES = frozenset(
    {"user", "assistant", "system", "summary", "custom-title", "file-history-snapshot"}
)

_WRAPPER = re.compile(
    r"<(system-reminder|command-name|command-message|command-args|command-contents"
    r"|local-command-stdout|local-command-stderr|local-command-caveat"
    r"|bash-input|bash-stdout|bash-stderr|task-notification|skill-format"
    r"|user-prompt-submit-hook)\b[^>]*>.*?</\1>",
    re.S,
)
_COMMAND_TAG = re.compile(r"<(command-name|local-command-[a-z]+|bash-[a-z]+)\b")
_COMMAND_NAME = re.compile(r"<command-name>(.*?)</command-name>", re.S)
_COMMAND_ARGS = re.compile(r"<command-args>(.*?)</command-args>", re.S)
_PASTE = re.compile(r"<pasted_content\b[^>]*>(.*?)</pasted_content\b[^>]*>", re.S)
_PASTE_TAG = re.compile(r"</?pasted_content\b[^>]*>")

_INTERRUPTED = "[Request interrupted by user"
_COMPACT_SUMMARY = "This session is being continued from a previous conversation"
# Text that Claude Code or a harness writes as a user line (as the probe parsers found).
_GENERATED = (
    "[SYSTEM NOTIFICATION",
    "Caveat: The messages below were generated by the user",
    "Base directory for this skill:",
    "# Workflow authoring reference",
)
# Input keys tried, in order, for a tool call's short summary.
_TOOL_KEYS = (
    "description", "command", "file_path", "notebook_path", "path", "pattern",
    "url", "query", "skill", "subagent_type", "prompt",
)
_USAGE_KEYS = (
    "input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens", "output_tokens",
)


@dataclass(slots=True)
class TurnUsage:
    """Token counts of one model response, as the transcript records them."""

    message_id: str
    timestamp: str | None
    model: str | None
    input_tokens: int = 0
    cache_creation_input_tokens: int = 0
    cache_read_input_tokens: int = 0
    output_tokens: int = 0
    request_id: str | None = None

    @property
    def context_tokens(self) -> int:
        """What the model read for this response: the context in use (DESIGN §3.1)."""
        return self.input_tokens + self.cache_creation_input_tokens + self.cache_read_input_tokens


@dataclass(slots=True)
class Compaction:
    """A point where Claude Code compacted the conversation."""

    timestamp: str | None
    trigger: str | None = None  # "auto" | "manual"
    pre_tokens: int | None = None  # the context just before


@dataclass(slots=True)
class ParsedSession:
    """One transcript: its chat record plus what the measures need besides the text."""

    source: Source
    path: str
    usage: list[TurnUsage] = field(default_factory=list)  # one per model response
    models: list[str] = field(default_factory=list)  # in order of first use
    compactions: list[Compaction] = field(default_factory=list)
    git_branches: list[str] = field(default_factory=list)  # in order of first use
    first_timestamp: str | None = None
    last_timestamp: str | None = None
    skipped: dict[str, int] = field(default_factory=dict)  # lines that became no message, by type
    versions: list[str] = field(default_factory=list)  # Claude Code versions
    entrypoints: list[str] = field(default_factory=list)  # e.g. "cli", "sdk-py"
    line_keys: set[str] = field(default_factory=set, repr=False)

    @property
    def id(self) -> str:
        return self.source.id

    @property
    def project(self) -> str | None:
        return self.source.project

    @property
    def git_branch(self) -> str | None:
        return self.git_branches[0] if self.git_branches else None

    @property
    def started(self) -> datetime | None:
        return parse_time(self.source.started_at)

    @property
    def ended(self) -> datetime | None:
        return parse_time(self.last_timestamp)

    def typed_turns(self) -> list[Message]:
        return self.source.user_messages()


def parse_time(value: object) -> datetime | None:
    """A transcript timestamp as an aware datetime; naive values are UTC."""
    if not isinstance(value, str) or not value:
        return None
    try:
        dt = datetime.fromisoformat(value)
    except ValueError:
        return None
    return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)


def as_datetime(value: datetime | date | str | None) -> datetime | None:
    """A bound a person gives, such as "2026-03-01"; naive values are local time."""
    if value is None:
        return None
    if isinstance(value, datetime):
        dt = value
    elif isinstance(value, date):
        dt = datetime.combine(value, time())
    else:
        dt = datetime.fromisoformat(value)
    return dt if dt.tzinfo else dt.astimezone()


def clean_text(raw: str) -> tuple[str, list[tuple[int, int]]]:
    """Remove Claude Code's wrappers; keep pasted text and return its offsets."""
    text = _WRAPPER.sub("", raw)
    pieces: list[str] = []
    ranges: list[tuple[int, int]] = []
    pos = size = 0
    for m in _PASTE.finditer(text):
        before = _PASTE_TAG.sub("", text[pos : m.start()])
        inner = m.group(1)
        pieces += [before, inner]
        size += len(before)
        ranges.append((size, size + len(inner)))
        size += len(inner)
        pos = m.end()
    pieces.append(_PASTE_TAG.sub("", text[pos:]))
    joined = "".join(pieces)
    lead = len(joined) - len(joined.lstrip())
    out = joined.strip()
    kept = []
    for start, end in ranges:
        start, end = max(start - lead, 0), min(end - lead, len(out))
        if end > start:
            kept.append((start, end))
    return out, kept


def tool_summary(name: str, tool_input: object) -> str:
    """The tool's name and a short summary of its input."""
    if isinstance(tool_input, dict):
        for key in _TOOL_KEYS:
            value = tool_input.get(key)
            if isinstance(value, str) and value.strip():
                first = value.strip().splitlines()[0]
                return f"{name}: {first if len(first) <= 120 else first[:119] + '…'}"
    return name


def line_keys(obj: dict) -> set[str]:
    """Keys that identify a line when a fork or an old-style resume copies it to another file."""
    keys = set()
    if isinstance(obj.get("uuid"), str):
        keys.add("u:" + obj["uuid"])
    if isinstance(obj.get("timestamp"), str) and isinstance(obj.get("message"), dict):
        body = json.dumps(obj["message"], sort_keys=True, ensure_ascii=False)
        digest = hashlib.sha1(body.encode("utf-8")).hexdigest()
        keys.add(f"c:{obj.get('type')}:{obj['timestamp']}:{digest}")
    return keys


def parse_session(path: Path | str, *, skip: set[str] | frozenset[str] = frozenset()) -> ParsedSession:
    """Parse one transcript. Lines whose keys are in `skip` belong to another session."""
    path = Path(path)
    reader = _Reader(skip)
    with path.open(encoding="utf-8", errors="replace") as fh:
        for raw in fh:
            reader.line(raw)
    return reader.result(path)


def parse_projects(root: Path | str, since: datetime | date | str | None = None) -> list[ParsedSession]:
    """Every session in the *.jsonl files below root, sorted by start time.

    A line copied into a later file (a fork, or a resume in older versions) is counted
    once, in the earliest session that holds it. Files left with no message, such as
    a subagent's sidechain file, are dropped. `since` keeps sessions that start then
    or later; earlier ones still own the lines they hold.
    """
    parsed = [parse_session(p) for p in sorted(Path(root).rglob("*.jsonl"))]
    parsed.sort(key=lambda s: (_sort_time(s.first_timestamp), _sort_time(s.last_timestamp), s.path))
    seen: set[str] = set()
    sessions = []
    for session in parsed:
        if session.line_keys & seen:
            session = parse_session(session.path, skip=seen)
        seen |= session.line_keys
        if session.source.messages:
            sessions.append(session)
    cutoff = as_datetime(since)
    if cutoff is not None:
        sessions = [s for s in sessions if s.started is not None and s.started >= cutoff]
    sessions.sort(key=lambda s: (_sort_time(s.source.started_at), s.path))
    return sessions


_EARLIEST = datetime.min.replace(tzinfo=timezone.utc)


def _sort_time(value: str | None) -> datetime:
    return parse_time(value) or _EARLIEST


def _add(seq: list[str], value: object) -> None:
    if isinstance(value, str) and value and value not in seq:
        seq.append(value)


def _int(value: object) -> int | None:
    return value if isinstance(value, int) and not isinstance(value, bool) else None


def _blocks(content: object) -> list[dict]:
    if isinstance(content, str):
        return [{"type": "text", "text": content}]
    if isinstance(content, list):
        return [b for b in content if isinstance(b, dict)]
    return []


class _Reader:
    """Reads the lines of one transcript in order."""

    def __init__(self, skip: set[str] | frozenset[str]) -> None:
        self.skip = skip
        self.skipped: Counter[str] = Counter()
        self.messages: list[Message] = []
        self.usage: dict[str, TurnUsage] = {}
        self.models: list[str] = []
        self.branches: list[str] = []
        self.versions: list[str] = []
        self.entrypoints: list[str] = []
        self.cwds: list[str] = []
        self.compactions: list[Compaction] = []
        self.keys: set[str] = set()
        self.uuids: set[str] = set()
        self.session_id: str | None = None
        self.summary: str | None = None
        self.custom_title: str | None = None
        self.first: tuple[datetime, str] | None = None
        self.last: tuple[datetime, str] | None = None
        self.boundary_open = False  # a compact_boundary not yet followed by its summary

    def line(self, raw: str) -> None:
        raw = raw.strip()
        if not raw:
            return
        try:
            obj = json.loads(raw)
        except ValueError:
            self.skipped["invalid_json"] += 1
            return
        if not isinstance(obj, dict):
            self.skipped["invalid_json"] += 1
            return
        keys = line_keys(obj)
        if keys & self.skip:
            self.skipped["copied"] += 1
            return
        uuid = obj.get("uuid")
        if isinstance(uuid, str):
            if uuid in self.uuids:
                self.skipped["duplicate"] += 1
                return
            self.uuids.add(uuid)
        self.keys |= keys
        ts = obj.get("timestamp") if isinstance(obj.get("timestamp"), str) else None
        self._clock(ts)
        if self.session_id is None and isinstance(obj.get("sessionId"), str):
            self.session_id = obj["sessionId"]

        kind = obj.get("type")
        if kind not in KNOWN_TYPES:
            self.skipped[f"unknown:{kind}"] += 1
            return
        if kind == "summary":
            if isinstance(obj.get("summary"), str):
                self.summary = obj["summary"]
            self.skipped["summary"] += 1
            return
        if kind == "custom-title":
            title = obj.get("customTitle") or obj.get("title")
            if isinstance(title, str):
                self.custom_title = title
            self.skipped["custom-title"] += 1
            return
        if kind == "file-history-snapshot":
            self.skipped[kind] += 1
            return
        if obj.get("isSidechain"):
            self.skipped["sidechain"] += 1
            return
        for seq, key in (
            (self.cwds, "cwd"),
            (self.branches, "gitBranch"),
            (self.versions, "version"),
            (self.entrypoints, "entrypoint"),
        ):
            _add(seq, obj.get(key))
        if kind == "system":
            self._system(obj, ts)
            return
        if obj.get("isMeta"):
            self.skipped["meta"] += 1
            return
        message = obj.get("message")
        if not isinstance(message, dict):
            self.skipped[f"{kind}:no_message"] += 1
            return
        if kind == "assistant":
            self._assistant(obj, message, ts)
        else:
            self._user(obj, message, ts)

    def _clock(self, ts: str | None) -> None:
        when = parse_time(ts)
        if when is None:
            return
        if self.first is None or when < self.first[0]:
            self.first = (when, ts)
        if self.last is None or when > self.last[0]:
            self.last = (when, ts)

    def _system(self, obj: dict, ts: str | None) -> None:
        if obj.get("subtype") != "compact_boundary":
            self.skipped["system"] += 1
            return
        meta = obj.get("compactMetadata") if isinstance(obj.get("compactMetadata"), dict) else {}
        trigger = meta.get("trigger") if isinstance(meta.get("trigger"), str) else None
        self.compactions.append(Compaction(ts, trigger, _int(meta.get("preTokens"))))
        self.boundary_open = True

    def _assistant(self, obj: dict, message: dict, ts: str | None) -> None:
        if obj.get("isApiErrorMessage"):
            self.skipped["api_error"] += 1
            return
        model = message.get("model") if isinstance(message.get("model"), str) else None
        if model == "<synthetic>":
            self.skipped["synthetic"] += 1
            return
        _add(self.models, model)
        mid = message.get("id") if isinstance(message.get("id"), str) else None
        mid = mid or (obj.get("uuid") if isinstance(obj.get("uuid"), str) else f"line-{len(self.uuids)}")
        usage = message.get("usage")
        if isinstance(usage, dict):
            self._usage(mid, ts, model, usage, obj.get("requestId"))
        produced = False
        for block in _blocks(message.get("content")):
            kind = block.get("type")
            if kind == "text" and isinstance(block.get("text"), str) and block["text"].strip():
                last = self.messages[-1] if self.messages else None
                if last is not None and last.speaker == "assistant" and last.meta.get("message_id") == mid:
                    last.text += "\n\n" + block["text"]  # one response, several text blocks
                else:
                    self._append(
                        "assistant", block["text"], ts, "assistant_output", obj,
                        model_family=FAMILY, message_id=mid, model=model,
                    )
                produced = True
            elif kind == "tool_use":
                name = block.get("name") if isinstance(block.get("name"), str) else "tool"
                self._append(
                    "tool", tool_summary(name, block.get("input")), ts, "tool_output", obj,
                    message_id=mid, tool=name,
                )
                produced = True
        if not produced and not isinstance(usage, dict):
            self.skipped["assistant:empty"] += 1

    def _usage(self, mid: str, ts: str | None, model: str | None, usage: dict, request_id: object) -> None:
        counts = {key: _int(usage.get(key)) or 0 for key in _USAGE_KEYS}
        record = self.usage.get(mid)
        if record is None:
            rid = request_id if isinstance(request_id, str) else None
            self.usage[mid] = TurnUsage(mid, ts, model, request_id=rid, **counts)
            return
        # One response written as several lines: count it once, at its largest.
        for key, value in counts.items():
            setattr(record, key, max(getattr(record, key), value))

    def _user(self, obj: dict, message: dict, ts: str | None) -> None:
        texts, images, results = [], 0, 0
        for block in _blocks(message.get("content")):
            kind = block.get("type")
            if kind == "text" and isinstance(block.get("text"), str):
                texts.append(block["text"])
            elif kind == "image":
                images += 1
            elif kind == "tool_result":
                results += 1
        raw = "\n".join(texts)
        if obj.get("isCompactSummary") or raw.lstrip().startswith(_COMPACT_SUMMARY):
            if self.boundary_open:
                self.boundary_open = False
            else:
                self.compactions.append(Compaction(ts))
            self.skipped["compact_summary"] += 1
            return

        meta: dict = {}
        name = _COMMAND_NAME.search(raw)
        if name:
            args = _COMMAND_ARGS.search(raw)
            args_text, pastes = clean_text(args.group(1)) if args else ("", [])
            if not args_text:
                self.skipped["command"] += 1
                return
            command = name.group(1).strip()
            command = command if command.startswith("/") else "/" + command
            text = f"{command} {args_text}"
            pastes = [(s + len(command) + 1, e + len(command) + 1) for s, e in pastes]
            meta["command"] = command
        else:
            text, pastes = clean_text(raw)

        if not text and not images:
            reason = "tool_result" if results else "command" if _COMMAND_TAG.search(raw) else "empty"
            self.skipped[reason] += 1
            return
        if text.startswith(_INTERRUPTED):
            self.skipped["interrupt"] += 1
            return
        if text.startswith(_GENERATED) or "automated background-task event" in text[:300]:
            self.skipped["generated"] += 1
            return
        if pastes:
            meta["paste_ranges"] = [list(r) for r in pastes]
        if images:
            meta["images"] = images
        origin = "pasted" if pastes == [(0, len(text))] else "typed"
        self._append("user", text, ts, origin, obj, **meta)

    def _append(
        self, speaker: str, text: str, ts: str | None, origin: str, obj: dict,
        model_family: str | None = None, **meta: object,
    ) -> None:
        uuid = obj.get("uuid") if isinstance(obj.get("uuid"), str) else None
        # Ids are set in result(), once the session id is known.
        self.messages.append(
            Message(
                id="", source_id="", ordinal=0, speaker=speaker, text=text, occurred_at=ts,
                origin=origin, agent=APP, model_family=model_family,
                meta={"uuid": uuid, **meta},
            )
        )

    def result(self, path: Path) -> ParsedSession:
        sid = self.session_id or path.stem
        for i, m in enumerate(self.messages):
            m.id, m.source_id, m.ordinal = f"{sid}:{i}", sid, i
        source = Source(
            id=sid,
            kind="chat",
            app=APP,
            project=self.cwds[0] if self.cwds else None,
            title=self.custom_title or self.summary,
            started_at=self.first[1] if self.first else None,
            messages=self.messages,
        )
        if len(self.cwds) > 1:
            source.meta["cwds"] = list(self.cwds)
        return ParsedSession(
            source=source,
            path=str(path),
            usage=list(self.usage.values()),
            models=self.models,
            compactions=self.compactions,
            git_branches=self.branches,
            first_timestamp=self.first[1] if self.first else None,
            last_timestamp=self.last[1] if self.last else None,
            skipped=dict(sorted(self.skipped.items())),
            versions=self.versions,
            entrypoints=self.entrypoints,
            line_keys=self.keys,
        )
